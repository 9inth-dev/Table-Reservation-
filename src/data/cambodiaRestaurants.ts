export function generateDailySlots(baseCapacity = 4): TimeSlot[] {
  const times: { time: string; period: 'lunch' | 'dinner'; isPrime?: boolean }[] = [
    { time: '11:30', period: 'lunch' },
    { time: '12:00', period: 'lunch' },
    { time: '12:30', period: 'lunch' },
    { time: '13:00', period: 'lunch' },
    { time: '17:30', period: 'dinner' },
    { time: '18:00', period: 'dinner' },
    { time: '18:30', period: 'dinner', isPrime: true },
    { time: '19:00', period: 'dinner', isPrime: true },
    { time: '19:30', period: 'dinner', isPrime: true },
    { time: '20:00', period: 'dinner', isPrime: true },
    { time: '20:30', period: 'dinner' },
    { time: '21:00', period: 'dinner' },
  ];

  return times.map((t, idx) => ({
    id: `slot-${t.time.replace(':', '')}`,
    time: t.time,
    period: t.period,
    availableCapacity: idx === 6 || idx === 8 ? Math.max(1, baseCapacity - 2) : baseCapacity,
    maxCapacity: baseCapacity,
    isPrime: t.isPrime,
  }));
}

